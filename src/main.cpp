#include <QApplication>

#include <algorithm>
#include <filesystem>
#include <format>
#include <iostream>

// MVC intentions
// What goes where in the MVC pattern can be a matter for debate; here's
// what goes where in this particular application:
//
// MODEL
// Any state data should go in a model, obviously.
// Any logic which supports checking of state, modification of state etc
// can also go in a model. Note there are multiple models (e.g. ShipModel);
// GameModel is the main one which contains the state of the game itself.
//
// VIEW
// Basically just code which interprets what it finds in a model and
// outputs it to the screen and speakers.
//
// CONTROLLER
// The "binding" between Model and View - this should contain logic
// related to the mechanics of the game BUT NOT logic related to actual
// gameplay (which should be in the model).

int main(int argc, char* argv[])
{
    using namespace marengo::amaze;

    try {

        std::filesystem::path exe(argv[0]);
        std::filesystem::path cwd = exe.remove_filename();
        cwd = std::filesystem::canonical(cwd);

        // Locate our resources (default values for e.g. Linux)
        std::string dataDir = (cwd / "data").string();
        std::string configDir = cwd.string();
        std::string logDir = cwd.string();
#ifdef __APPLE__
        // If on MacOS, this app is designed to work inside a "bundle", i.e.
        // amaze.app/
        // └── Contents/
        //     ├── Info.plist          ← generated by CMake
        //     ├── MacOS/
        //     │   └── amaze           ← the binary
        //     ├── Frameworks/
        //     │   └── *.dylib         ← bundled dylibs (copied by dylibbundler)
        //     └── Resources/
        //         ├── amaze.icns      ← app icon
        //         ├── amaze.cfg       ← runtime config
        //         └── data/           ← runtime data
        if (std::filesystem::exists(cwd.parent_path() / "Resources")) {
            dataDir = (cwd.parent_path() / "Resources/data").string();
            configDir = (cwd.parent_path() / "Resources").string();
        }
        const char* home = getenv("HOME");
        logDir = std::string(home) + "/Library/Logs/amaze";
        std::filesystem::create_directories(logDir);
#endif
        mgo::ConfigReader config(std::format("{}/amaze.cfg", configDir));
        mgo::Log::init(std::format("{}/amaze.log", logDir));
        mgo::Log::info("Starting amaze");

        ProgramOptions programOptions(argc, argv);
        if (programOptions.cmdOptionExists("-h") || programOptions.cmdOptionExists("--help")) {
            std::cout
                << "Usage: amaze [-h|--help] [-f|--fullscreen] [-w|--windowed] [--file <level "
                   "FILE>] [-l <level number>]"
                << std::endl;
            return 0;
        }

        QApplication app(argc, argv);
        // These determine where settings are saved
        QCoreApplication::setOrganizationName("marengo");
        QCoreApplication::setApplicationName("amaze");
        Settings settings;

        // Precedence for options: command line, then settings saved from the
        // last run, then amaze.cfg (which therefore only supplies defaults for
        // the first run).

        // The window's dimensions' proportions should mirror the physical screen's dimensions so
        // everything is in proportion if we go fullscreen
        int width = config.readLong("WindowWidth", 800);
        int height = config.readLong("WindowHeight", 500);
        bool useFullScreen = settings.fullScreen().value_or(config.readBool("FullScreen", false));
        if (programOptions.cmdOptionExists("-f")
            || programOptions.cmdOptionExists("--fullscreen")) {
            useFullScreen = true;
        }
        if (programOptions.cmdOptionExists("-w") || programOptions.cmdOptionExists("--windowed")) {
            useFullScreen = false;
        }

        // Level to start with: a level FILE or number from the command line,
        // otherwise the last level played, otherwise the level number from
        // amaze.cfg
        int gameLevel = config.readLong("GameLevel", 0);
        std::string levelFile;
        if (programOptions.cmdOptionExists("--file")) {
            levelFile = programOptions.getCmdOption("--file");
        } else if (programOptions.cmdOptionExists("-l")) {
            gameLevel = std::atoi(programOptions.getCmdOption("-l").c_str());
        } else if (auto lastLevel = settings.lastLevelFile()) {
            std::filesystem::path lastLevelPath(*lastLevel);
            if (std::filesystem::exists(lastLevelPath)) {
                levelFile = lastLevelPath.string();
            } else if (
                auto moved = std::filesystem::path(dataDir) / lastLevelPath.filename();
                std::filesystem::exists(moved)) {
                // e.g. the app has moved since
                levelFile = moved.string();
            }
        }

        MenuResults menuValues;
        menuValues.musicVolumePercent
            = settings.musicVolumePercent().value_or(menuValues.musicVolumePercent);
        // Clamped in case it was saved by a version that allowed other values
        menuValues.stickDeadZonePercent = std::clamp(
            settings.stickDeadZonePercent().value_or(menuValues.stickDeadZonePercent),
            MIN_STICK_DEAD_ZONE_PERCENT,
            MAX_STICK_DEAD_ZONE_PERCENT);
        menuValues.rumbleIntensityPercent = std::clamp(
            settings.rumbleIntensityPercent().value_or(menuValues.rumbleIntensityPercent), 0, 100);

        Audio audio;
        GameShell shell(
            width, height, settings.windowGeometry(), useFullScreen, menuValues, dataDir);

        GameModel gameModel(dataDir);
        View view(gameModel, audio, dataDir);

        Controller controller(gameModel, view, shell, audio, settings);
        controller.start(gameLevel, levelFile);
        // Qt owns the event loop, and calls the controller once per displayed frame
        shell.run([&](QPainter& painter, const QSizeF& canvasSize) {
            return controller.frame(painter, canvasSize);
        });

        settings.setFullScreen(shell.isFullScreen());
        if (shell.windowGeometry().isValid()) {
            settings.setWindowGeometry(shell.windowGeometry());
        }

        return 0;
    } catch (const marengo::amaze::AmazeBaseException& ex) {
        // Logged against the throw site rather than here
        mgo::Log::error(ex.what(), ex.location());
        std::cout << std::format(
            "Exception ({0}) thrown in {1} +{2} ({3}) : {4}\n",
            typeid(ex).name(),
            ex.location().file_name(),
            ex.location().line(),
            ex.location().function_name(),
            ex.what())
                  << std::endl;
    } catch (const std::exception& e) {
        mgo::Log::error(std::format("Exception encountered: {}", e.what()));
        std::cout << std::format("Exception encountered: {}\n", e.what()) << std::endl;
    }
    return 1;
}
